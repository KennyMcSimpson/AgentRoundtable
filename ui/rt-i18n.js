  function t(lang, key, params) {
    var l = normalizeLang(lang);
    var table = DICT[l] || DICT[DEFAULT_LANG];
    var s = Object.prototype.hasOwnProperty.call(table, key)
      ? table[key]
      : (Object.prototype.hasOwnProperty.call(DICT[DEFAULT_LANG], key) ? DICT[DEFAULT_LANG][key] : key);
    if (!params) return s;
    return String(s).replace(/\{([A-Za-z0-9_]+)\}/g, function (_, name) {
      return Object.prototype.hasOwnProperty.call(params, name) && params[name] !== undefined && params[name] !== null
        ? String(params[name])
        : '';
    });
  }

